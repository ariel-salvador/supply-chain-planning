"""Compare Odoo's replenishment plan with the Python engine's MRP.

    .venv/bin/python scripts/compare_plans.py products/blg_whey_protein.yaml

Reads data/processed/odoo_plan.csv (from odoo_run.py) and outputs/odoo/seed_meta.json
(from odoo_seed.py), reruns the engine on the same config, and writes
docs/odoo/comparison.md. Odoo dates are converted to week offsets from the seed's
week-0 Monday; the engine's weeks are its bucket indices. Orders that existed at
the start (WIP / open POs) and the draft RFQs of the sourcing round are excluded from
both sides' planned figures.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ppsim import bom as bom_mod  # noqa: E402
from ppsim.config import load_config  # noqa: E402
from ppsim.pipeline import run  # noqa: E402

PLAN = ROOT / "data" / "processed" / "odoo_plan.csv"
META = ROOT / "outputs" / "odoo" / "seed_meta.json"
REPORT = ROOT / "docs" / "odoo" / "comparison.md"


def week_of(ts: pd.Series, anchor: dt.date, days: float) -> pd.Series:
    d = (pd.to_datetime(ts).dt.normalize() - pd.Timestamp(anchor)).dt.days
    return np.floor(d / days).astype(int)


def span(weeks) -> str:
    weeks = list(weeks)
    if not weeks:
        return "–"
    lo, hi = min(weeks), max(weeks)
    fmt = lambda w: f"w{w}" if w >= 0 else f"before w0"  # noqa: E731
    return fmt(lo) if lo == hi else f"{fmt(lo)} … {fmt(hi)}"


def md_table(df: pd.DataFrame) -> str:
    cols = [str(c) for c in df.columns]
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        out.append("| " + " | ".join(str(v) for v in r.values) + " |")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("config", type=Path)
    args = ap.parse_args()

    meta = json.loads(META.read_text())
    anchor = dt.date.fromisoformat(meta["anchor_week0"])
    days = float(meta["days_per_week"])

    cfg = load_config(args.config)
    res = run(cfg, fetch_prices=False)
    items = bom_mod.reachable(cfg.demand.item, cfg.bom)

    odoo = pd.read_csv(PLAN)
    odoo = odoo[~odoo["open_at_start"].astype(bool)].copy()
    if "rfq" in odoo.columns:  # draft RFQs are quotes from the sourcing round, not a plan
        odoo = odoo[~odoo["rfq"].astype(bool)].copy()
    odoo["start_w"] = week_of(odoo["start"], anchor, days)
    odoo["due_w"] = week_of(odoo["due"], anchor, days)

    rows, profiles = [], {}
    for iid in items:
        t = res.mrp[iid].table
        rec = t.loc["planned_order_receipts"].to_numpy()
        rel = t.loc["planned_order_releases"].to_numpy()
        py_weeks = [w for w, q in enumerate(rec) if q > 1e-9]
        o = odoo[odoo["item"] == iid]
        py_q, od_q = rec.sum(), o["qty"].sum()
        rel_w = (np.arange(len(rel)) * rel).sum() / rel.sum() if rel.sum() else float("nan")
        od_w = (o["start_w"] * o["qty"]).sum() / od_q if od_q else float("nan")
        rows.append({
            "item": iid,
            "kind": "PO" if cfg.items[iid].type == "purchased" else "MO",
            "engine qty": f"{py_q:,.0f}",
            "Odoo qty": f"{od_q:,.0f}",
            "Δ %": f"{(od_q - py_q) / py_q * 100:+.0f}%" if py_q else "–",
            "engine orders": len(py_weeks),
            "Odoo orders": len(o),
            "engine receipts": span(py_weeks),
            "Odoo due": span(o["due_w"]),
            "avg start week (engine → Odoo)": f"{rel_w:.1f} → {od_w:.1f}" if od_q and rel.sum() else "–",
        })
        h = len(rec)
        od_by_w = o.groupby(o["due_w"].clip(lower=0))["qty"].sum().reindex(range(h), fill_value=0).to_numpy()
        profiles[iid] = (np.cumsum(rec), np.cumsum(od_by_w))

    summary = pd.DataFrame(rows)
    show = [i for i in (cfg.demand.item, "BLG-FERM", "GLUCOSE") if i in profiles] or items[:3]
    weeks = [0, 1, 2, 4, 8, 12, 17, 25]
    prof_rows = []
    for iid in show:
        py, od = profiles[iid]
        for label, arr in (("engine", py), ("Odoo", od)):
            prof_rows.append({"item": iid, "plan": label, **{f"w{w}": f"{arr[w]:,.0f}" for w in weeks if w < len(arr)}})
    profile = pd.DataFrame(prof_rows)

    sop_end = res.mps.table.loc["projected_available_balance"].iloc[-1] if res.mps is not None else float("nan")
    fg_ss = cfg.items[cfg.demand.item].planning.safety_stock

    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(f"""# Odoo vs Python engine: planned orders

_Generated by `scripts/compare_plans.py` from `{args.config}`. Demand, starting stock
and lot policies are [mock]; process quantities are [source] (see
`knowledge/assumptions.csv`). Odoo 19.0 Community, week 0 = {anchor} in Odoo and
{cfg.start} in the engine._

## Per item (planned orders only; WIP and open POs at start excluded)

{md_table(summary)}

## Cumulative planned supply by week (receipt/due week)

{md_table(profile)}

## Why they differ

1. **Timing is the big one.** Odoo's reorder rules look ahead `lead time + horizon_days`
   (set to the engine's {cfg.horizon}-week horizon) and replenish every shortfall they
   see **now**: MOs start today, and RFQs are dated today and due after the vendor lead
   time. The engine is time-phased, so each planned order is released in the week it's
   needed. Odoo's time-phased equivalent, the Master Production Schedule, is
   Enterprise-only (ADR 0009). In Community, time-phasing comes from running the
   scheduler daily with a short horizon, not from a single run.
2. **Quantities.** Odoo covers confirmed sales orders down to the reorder minimum
   (safety stock {fg_ss:,.0f} kg for powder). The engine's MPS follows the S&OP plan,
   which also builds inventory to its months-of-cover target, so the engine ends the
   horizon with about {sop_end:,.0f} kg of powder on hand. Where the engine plans more,
   that's inventory build, not extra demand.
3. **Order counts.** Odoo creates one MO per demand shortfall it resolves (roughly one
   per sales order) and groups purchase lines into RFQs per vendor. The engine creates
   at most one order per item per week.
4. **Lot sizes agree.** Both round fermentation to whole 12,000 kg batches (Odoo via a
   batch unit on the reorder rule) and sugar to 250 t lots.
5. **Lead times.** Odoo uses days (weeks × 7); the engine uses whole weeks. The 144 h
   fermentation cycle is 7 days in both, because the engine rounds it up to 1 week.

## What each tool does well

| | Python engine | Odoo Community |
|---|---|---|
| S&OP / MPS / capacity | yes: monthly S&OP, MPS with fences and ATP, capacity caps | no (MPS and Gantt are Enterprise) |
| Time-phased plan | yes: weekly buckets over the horizon | only by running the scheduler repeatedly |
| Transactions | none (a planning model) | real MOs, RFQs/POs, stock moves, reservations, receipts |
| Traceability of numbers | every number cited or [mock] in a registry | data lives in the database |
| Best use | explaining and testing planning policy | executing the plan day to day |
""")
    print(f"wrote {REPORT.relative_to(ROOT)}")
    print(summary[["item", "engine qty", "Odoo qty", "Δ %", "engine orders", "Odoo orders", "engine receipts", "Odoo due"]].to_string(index=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
